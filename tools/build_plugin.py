#!/usr/bin/env python3
"""Package the plugin as a ZIP that TRMNL's private plugin importer accepts.

The importer expects a flat archive: settings.yml plus one .liquid file per
view size. It has no slot for a shared partials file, so shared.liquid is
prepended to each view — which is exactly what TRMNL does with the Shared tab
at render time.
"""

import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
VIEWS = ["full", "half_horizontal", "half_vertical", "quadrant"]

SETTINGS = """---
name: Rivian
strategy: webhook
refresh_interval: 15
no_screen_padding: 'no'
dark_mode: 'no'
"""

# str.format is unusable here — the template language uses the same braces.
BANNER = """{%- comment -%}
  Rivian for TRMNL — generated by tools/build_plugin.py, do not edit here.
  Source: plugin/shared.liquid + plugin/__VIEW__.liquid
{%- endcomment -%}
"""


def main():
    shared = (ROOT / "plugin" / "shared.liquid").read_text()
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    archive = dist / "trmnl-rivian.zip"

    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("settings.yml", SETTINGS)
        for view in VIEWS:
            body = (ROOT / "plugin" / f"{view}.liquid").read_text()
            z.writestr(f"{view}.liquid", BANNER.replace("__VIEW__", view) + shared + "\n" + body)

    for info in zipfile.ZipFile(archive).infolist():
        print(f"  {info.filename:<26} {info.file_size:>6} B")
    print(f"\n{archive.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
